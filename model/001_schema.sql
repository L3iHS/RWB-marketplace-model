-- Структура core. Вызывается внутри транзакции сборки; raw не меняется.
-- IF NOT EXISTS поддерживает повторную сборку этой версии, но не миграции схемы.
CREATE SCHEMA IF NOT EXISTS core;

CREATE TABLE IF NOT EXISTS core.customers (
    customer_unique_id text PRIMARY KEY
);
COMMENT ON TABLE core.customers IS 'Одна строка — покупатель с устойчивым исходным customer_unique_id.';

CREATE TABLE IF NOT EXISTS core.customer_order_profiles (
    customer_id text PRIMARY KEY,
    customer_unique_id text NOT NULL REFERENCES core.customers,
    zip_code_prefix text,
    city text,
    state text
);
COMMENT ON TABLE core.customer_order_profiles IS 'Одна исходная запись customer_id; сохраняет адресный контекст заказа. Не текущее местоположение человека.';
CREATE INDEX IF NOT EXISTS customer_order_profiles_customer_unique_id_idx ON core.customer_order_profiles (customer_unique_id);

CREATE TABLE IF NOT EXISTS core.order_statuses (
    status_code text PRIMARY KEY,
    is_delivered boolean NOT NULL
);
COMMENT ON TABLE core.order_statuses IS 'Статусы источника. is_delivered=true только для delivered; неизвестные новые статусы требуют проверки правил.';

CREATE TABLE IF NOT EXISTS core.payment_types (
    payment_type text PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS core.categories (
    category_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_pt text UNIQUE NULLS NOT DISTINCT,
    name_en text
);
COMMENT ON TABLE core.categories IS 'Одна исходная категория. ID сохраняется при пересборках и изменении набора категорий. name_pt=NULL — отсутствие категории; отсутствие перевода — другой случай.';

CREATE TABLE IF NOT EXISTS core.products (
    product_id text PRIMARY KEY,
    category_id bigint NOT NULL REFERENCES core.categories,
    name_length integer,
    description_length integer,
    photos_qty integer,
    weight_g integer,
    length_cm integer,
    height_cm integer,
    width_cm integer
);
CREATE INDEX IF NOT EXISTS products_category_id_idx ON core.products (category_id);

CREATE TABLE IF NOT EXISTS core.sellers (
    seller_id text PRIMARY KEY,
    zip_code_prefix text,
    city text,
    state text
);

CREATE TABLE IF NOT EXISTS core.orders (
    order_id text PRIMARY KEY,
    customer_id text NOT NULL REFERENCES core.customer_order_profiles,
    status_code text NOT NULL REFERENCES core.order_statuses,
    purchased_at timestamp NOT NULL,
    approved_at timestamp,
    delivered_carrier_at timestamp,
    delivered_customer_at timestamp,
    estimated_delivery_at timestamp,
    source_file text NOT NULL,
    source_loaded_at timestamptz NOT NULL
);
COMMENT ON TABLE core.orders IS 'Один заказ, включая отменённые и незавершённые. Даты источника без часового пояса; часовой пояс не додумываем.';
CREATE INDEX IF NOT EXISTS orders_customer_id_idx ON core.orders (customer_id);
CREATE INDEX IF NOT EXISTS orders_purchased_at_idx ON core.orders (purchased_at);

CREATE TABLE IF NOT EXISTS core.order_items (
    order_id text NOT NULL REFERENCES core.orders,
    order_item_id integer NOT NULL CHECK (order_item_id > 0),
    product_id text NOT NULL REFERENCES core.products,
    seller_id text NOT NULL REFERENCES core.sellers,
    shipping_limit_at timestamp,
    price numeric NOT NULL,
    freight_value numeric NOT NULL,
    source_file text NOT NULL,
    source_loaded_at timestamptz NOT NULL,
    PRIMARY KEY (order_id, order_item_id)
);
COMMENT ON TABLE core.order_items IS 'Одна исходная позиция = одна единица товара. Повторные одинаковые товары не схлопываем. Деньги numeric без округления при загрузке.';
CREATE INDEX IF NOT EXISTS order_items_product_id_idx ON core.order_items (product_id);
CREATE INDEX IF NOT EXISTS order_items_seller_id_idx ON core.order_items (seller_id);

CREATE TABLE IF NOT EXISTS core.order_payments (
    order_id text NOT NULL REFERENCES core.orders,
    payment_sequential integer NOT NULL CHECK (payment_sequential > 0),
    payment_type text NOT NULL REFERENCES core.payment_types,
    installments integer NOT NULL,
    payment_value numeric NOT NULL,
    source_file text NOT NULL,
    source_loaded_at timestamptz NOT NULL,
    PRIMARY KEY (order_id, payment_sequential)
);
COMMENT ON COLUMN core.order_payments.installments IS 'Количество частей рассрочки, включая исходные нули. Не множитель payment_value и не число записей платежей.';
CREATE INDEX IF NOT EXISTS order_payments_payment_type_idx ON core.order_payments (payment_type);

CREATE TABLE IF NOT EXISTS core.order_reviews (
    review_id text NOT NULL,
    order_id text NOT NULL REFERENCES core.orders,
    score integer NOT NULL CHECK (score BETWEEN 1 AND 5),
    comment_title text,
    comment_message text,
    created_at timestamp,
    answered_at timestamp,
    source_file text NOT NULL,
    source_loaded_at timestamptz NOT NULL,
    PRIMARY KEY (review_id, order_id)
);
COMMENT ON TABLE core.order_reviews IS 'Одна исходная запись отзыва. review_id сам по себе не уникален, у заказа может быть несколько отзывов.';
CREATE INDEX IF NOT EXISTS order_reviews_order_id_idx ON core.order_reviews (order_id);
